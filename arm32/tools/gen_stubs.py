#!/usr/bin/env python3
"""Generates a guest stub library and its host numbers from a list file.

The list has one entry per line:
  name              a function: a stub that traps to the host with the next simple number
  !name             the same, with a reentrant number (the host may call guest code)
  data NAME HEX     an exported 16-byte constant (an OpenSL interface ID), reached through
                    the exported pointer NAME, as the real library does
Lines starting with # are comments.

  gen_stubs.py <list> <simple base> <reentrant base> <out.S> <out.h> <prefix>
writes the stubs (assembled into the guest library) and constexpr numbers named
<prefix><name> for the host side.
"""
import sys

lst, simple_base, reentrant_base, out_s, out_h, prefix = sys.argv[1:7]
simple, reentrant = int(simple_base, 0), int(reentrant_base, 0)
asm = [
    f"// Generated by arm32/tools/gen_stubs.py from {lst.split('/')[-1]}. Do not edit.",
    "    .syntax unified", "    .arm", "    .text",
    ".macro trap name, number",
    "    .global \\name", "    .type \\name, %function", "    .balign 4", "\\name:",
    "    push {r7, lr}", "    movw r7, #(\\number & 0xffff)", "    movt r7, #(\\number >> 16)",
    "    svc #0", "    pop {r7, pc}", "    .size \\name, . - \\name", ".endm",
]
data = ["    .data"]
header = [f"// Generated by arm32/tools/gen_stubs.py from {lst.split('/')[-1]}. Do not edit.", "#pragma once", "#include <cstdint>", "namespace arm32 {"]
data_names = []
for line in open(lst):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    if line.startswith("data "):
        _, name, value = line.split()
        data_names.append(name)
        data += [f"    .balign 4", f"{name}_value:", "    .byte " + ", ".join(f"0x{value[i:i+2]}" for i in range(0, 32, 2)),
                 f"    .global {name}", f"    .type {name}, %object", f"{name}:", f"    .word {name}_value", f"    .size {name}, 4"]
        continue
    if line.startswith("!"):
        name, number = line[1:], reentrant
        reentrant += 1
    else:
        name, number = line, simple
        simple += 1
    asm.append(f"    trap {name}, {number:#x}")
    header.append(f"constexpr std::uint32_t {prefix}{name} = {number:#x};")
if data_names:
    header.append(f"inline constexpr const char* {prefix}data_names[] = {{" + ", ".join(f'"{n}"' for n in data_names) + "};")
    header.append(f"inline constexpr unsigned {prefix}data_count = {len(data_names)};")
header.append("}  // namespace arm32")
open(out_s, "w").write("\n".join(asm + data + ['    .section .note.GNU-stack, "", %progbits']) + "\n")
open(out_h, "w").write("\n".join(header) + "\n")
